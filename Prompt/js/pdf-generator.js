  static generateQuizPDF(data) {
    const ctx = this.createDocContext();
    const { doc, marginLeft, contentWidth } = ctx;
    const { metadata = {}, quiz = [] } = data;

    ctx.headerTitle = `${metadata.title || 'Lecture Revision'} — 5-Question Practice Quiz`;

    // 1. Header Banner
    const title = `${metadata.title || "Lecture"} — Practice Quiz`;
    const subtitle = "Diagnostic Practice Assessment & Detailed Answer Key";
    const meta = [
      `Questions: ${quiz.length}`,
      `Subject: ${metadata.subject?.toUpperCase() || "GENERAL"}`,
      `Date: ${metadata.generatedAt || new Date().toLocaleDateString()}`
    ];
    this.drawBanner(ctx, title, subtitle, meta);

    // 2. Instructions Box
    ctx.checkPageBreak(42);
    doc.setFillColor(248, 250, 252);
    doc.setDrawColor(226, 232, 240);
    doc.roundedRect(marginLeft, ctx.currentY, contentWidth, 34, 4, 4, 'FD');
    doc.setFont("helvetica", "bold");
    doc.setFontSize(8.5);
    doc.setTextColor(71, 85, 105);
    doc.text("INSTRUCTIONS FOR STUDENTS:", marginLeft + 12, ctx.currentY + 14);
    doc.setFont("helvetica", "normal");
    doc.text("Answer questions 1-5 without looking at the answer key. Turn to the final section for verified answers & diagnostic rationales.", marginLeft + 12, ctx.currentY + 26);
    ctx.currentY += 46;

    // 3. Quiz Questions Section
    this.drawSectionHeader(ctx, "5 Diagnostic Practice Questions", "📝", [99, 102, 241]);

    quiz.forEach((q, qIdx) => {
      doc.setFont("helvetica", "bold");
      doc.setFontSize(10);
      const qPromptLines = doc.splitTextToSize(`Q${qIdx + 1}: ${q.question}`, contentWidth - 28);
      
      // Compute option heights
      const optionLineBlocks = q.options.map((opt, oIdx) => {
        const letter = String.fromCharCode(65 + oIdx);
        doc.setFont("helvetica", "normal");
        doc.setFontSize(9);
        return {
          letter,
          lines: doc.splitTextToSize(`[   ]   ${letter})  ${opt}`, contentWidth - 36)
        };
      });

      let qTotalHeight = 16 + (qPromptLines.length * 13) + 10;
      optionLineBlocks.forEach(blk => {
        qTotalHeight += (blk.lines.length * 12) + 6;
      });
      qTotalHeight += 12;

      ctx.checkPageBreak(qTotalHeight);

      // Question card
      doc.setFillColor(255, 255, 255);
      doc.setDrawColor(226, 232, 240);
      doc.roundedRect(marginLeft, ctx.currentY, contentWidth, qTotalHeight, 5, 5, 'FD');

      // Question Prompt
      doc.setFont("helvetica", "bold");
      doc.setFontSize(10);
      doc.setTextColor(15, 23, 42);
      doc.text(qPromptLines, marginLeft + 12, ctx.currentY + 16);

      let optY = ctx.currentY + 16 + (qPromptLines.length * 13) + 6;

      // Options
      optionLineBlocks.forEach((blk) => {
        doc.setFont("helvetica", "normal");
        doc.setFontSize(9);
        doc.setTextColor(51, 65, 85);
        doc.text(blk.lines, marginLeft + 18, optY);
        optY += (blk.lines.length * 12) + 6;
      });

      // Citation at bottom right
      if (q.citation) {
        doc.setFont("helvetica", "italic");
        doc.setFontSize(7.5);
        doc.setTextColor(148, 163, 184);
        doc.text(`Reference: ${q.citation}`, marginLeft + contentWidth - 14, ctx.currentY + qTotalHeight - 6, { align: 'right' });
      }

      ctx.currentY += qTotalHeight + 10;
    });

    // 4. Force Page Break to Answer Key & Rationales
    doc.addPage();
    ctx.pageCount++;
    ctx.currentY = ctx.marginTop + 24;
    ctx.drawRunningHeader();

    this.drawSectionHeader(ctx, "Answer Key & Diagnostic Rationales", "🎯", [16, 185, 129]);

    quiz.forEach((q, qIdx) => {
      const correctLetter = String.fromCharCode(65 + q.correctIndex);
      const correctOptionText = q.options[q.correctIndex];

      doc.setFont("helvetica", "bold");
      doc.setFontSize(10);
      const headerText = `Q${qIdx + 1} Answer: Option ${correctLetter} — "${correctOptionText}"`;
      
      doc.setFont("helvetica", "normal");
      doc.setFontSize(9);
      const expLines = doc.splitTextToSize(`Explanation: ${q.explanation}`, contentWidth - 28);
      
      let distractorLines = [];
      if (Array.isArray(q.distractorExplanations) && q.distractorExplanations.length > 0) {
        const dText = q.distractorExplanations.join("\n");
        distractorLines = doc.splitTextToSize(`Distractor Analysis:\n${dText}`, contentWidth - 28);
      }

      let cardHeight = 22 + (expLines.length * 12) + 12;
      if (distractorLines.length > 0) {
        cardHeight += (distractorLines.length * 11) + 8;
      }

      ctx.checkPageBreak(cardHeight);

      // Card
      doc.setFillColor(240, 253, 244); // emerald-50
      doc.setDrawColor(187, 247, 208); // emerald-200
      doc.roundedRect(marginLeft, ctx.currentY, contentWidth, cardHeight, 4, 4, 'FD');

      // Header
      doc.setFont("helvetica", "bold");
      doc.setFontSize(9.5);
      doc.setTextColor(4, 120, 87); // emerald-700
      doc.text(headerText, marginLeft + 12, ctx.currentY + 16);

      // Explanation
      doc.setFont("helvetica", "normal");
      doc.setFontSize(9);
      doc.setTextColor(6, 78, 59); // emerald-900
      doc.text(expLines, marginLeft + 12, ctx.currentY + 30);

      // Distractors if available
      if (distractorLines.length > 0) {
        const dY = ctx.currentY + 30 + (expLines.length * 12) + 4;
        doc.setFont("helvetica", "italic");
        doc.setFontSize(8);
        doc.setTextColor(71, 85, 105);
        doc.text(distractorLines, marginLeft + 12, dY);
      }

      ctx.currentY += cardHeight + 8;
    });

    ctx.drawRunningFooters();
    return doc;
  }

